import zipfile
import glob
import os
import pandas as pd
import numpy as np
import unicodedata
import warnings

warnings.filterwarnings('ignore', category=UnicodeWarning)

def normalizar_texto(texto):
    texto = unicodedata.normalize('NFD', texto)
    texto = "".join([c for c in texto if unicodedata.category(c) != 'Mn'])
    return " ".join(texto.lower().split())

def leer_archivo_interno_seguro(z, nombre_archivo):
    ext = nombre_archivo.lower().split('.')[-1]
    with z.open(nombre_archivo) as f:
        if 'csv' in ext:
            primera_linea = f.readline().decode('latin-1', errors='ignore')
            separador = ';' if ';' in primera_linea else ','
            f.seek(0)
            return pd.read_csv(f, sep=separador, encoding='latin-1', low_memory=False)
        elif 'sav' in ext:
            try:
                import pyreadstat
                temp_path = f"/tmp/{os.path.basename(nombre_archivo)}"
                with open(temp_path, 'wb') as tmp_f:
                    tmp_f.write(f.read())
                df, _ = pyreadstat.read_sav(temp_path)
                os.remove(temp_path)
                return df
            except ImportError:
                raise RuntimeError("Se requiere 'pyreadstat' para archivos .sav")
        elif 'dta' in ext:
            temp_path = f"/tmp/{os.path.basename(nombre_archivo)}"
            with open(temp_path, 'wb') as tmp_f:
                tmp_f.write(f.read())
            df = pd.read_stata(temp_path, convert_categoricals=False)
            os.remove(temp_path)
            return df
    raise ValueError(f"Formato no soportado: {ext}")

